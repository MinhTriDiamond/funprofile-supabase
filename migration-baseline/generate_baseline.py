import json
from pathlib import Path
from collections import defaultdict

SNAP = Path("migration-snapshot")
OUT = Path("migration-baseline")
OUT.mkdir(exist_ok=True)

def load(name):
    with open(SNAP / name) as f:
        return json.load(f)["rows"]

def qi(name):
    return '"' + name.replace('"', '""') + '"'

# ---------- ENUMS ----------
enum_rows = load("02-enums.json")
enums = defaultdict(list)
for r in enum_rows:
    enums[r["type_name"]].append(r["enumlabel"])

# ---------- SEQUENCES ----------
seqs = load("03-sequences.json")

# ---------- EXACT COLUMNS ----------
cols = load("08-exact-columns.json")
by_table = defaultdict(list)
for r in cols:
    by_table[r["table_name"]].append(r)

# ---------- CONSTRAINTS ----------
constraints = load("05-constraints.json")

# ---------- INDEXES ----------
indexes = load("09-standalone-indexes.json")

# ---------- RLS ----------
rls = load("07-rls-flags.json")

# ============================================================
# B1
# ============================================================
b1 = []
b1.append("-- AUTO-GENERATED FUN Profile baseline")
b1.append("-- B1: foundation")
b1.append("BEGIN;")
b1.append("")

# Extensions required by observed defaults / source inventory.
b1 += [
    'CREATE EXTENSION IF NOT EXISTS pgcrypto WITH SCHEMA extensions;',
    'CREATE EXTENSION IF NOT EXISTS "uuid-ossp" WITH SCHEMA extensions;',
    ""
]

for typ in sorted(enums):
    labels = ", ".join("'" + x.replace("'", "''") + "'" for x in enums[typ])
    b1.append(f"CREATE TYPE public.{qi(typ)} AS ENUM ({labels});")

b1.append("")

for r in seqs:
    name = qi(r["sequencename"])
    data_type = r["data_type"]
    start = r["start_value"]
    minv = r["min_value"]
    maxv = r["max_value"]
    inc = r["increment_by"]
    cycle = "CYCLE" if r["cycle"] else "NO CYCLE"

    b1.append(
        f"CREATE SEQUENCE public.{name} "
        f"AS {data_type} "
        f"INCREMENT BY {inc} "
        f"MINVALUE {minv} "
        f"MAXVALUE {maxv} "
        f"START WITH {start} "
        f"{cycle};"
    )

b1.append("")

b1.append(r"""
CREATE OR REPLACE FUNCTION public.gen_post_share_code()
RETURNS text
LANGUAGE plpgsql
SET search_path TO 'public', 'extensions'
AS $function$
DECLARE
  alphabet text := '0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz';
  code text := '';
  i int;
  bytes bytea;
BEGIN
  bytes := extensions.gen_random_bytes(10);
  FOR i IN 0..9 LOOP
    code := code || substr(alphabet, (get_byte(bytes, i) % 62) + 1, 1);
  END LOOP;
  RETURN code;
END;
$function$;
""".strip())

b1.append("")
b1.append("COMMIT;")

(OUT / "B1-foundation.sql").write_text("\n".join(b1) + "\n")

# ============================================================
# B2
# ============================================================
b2 = []
b2.append("-- AUTO-GENERATED FUN Profile baseline")
b2.append("-- B2: tables")
b2.append("BEGIN;")
b2.append("")

for table in sorted(by_table):
    definitions = []

    for r in sorted(by_table[table], key=lambda x: x["ordinal_position"]):
        parts = [qi(r["column_name"]), r["formatted_type"]]

        generated = r.get("generated_kind") or ""
        identity = r.get("identity_kind") or ""
        expr = r.get("default_expression")

        if generated:
            if expr:
                parts.append(f"GENERATED ALWAYS AS ({expr}) STORED")
        elif identity:
            if identity == "a":
                parts.append("GENERATED ALWAYS AS IDENTITY")
            elif identity == "d":
                parts.append("GENERATED BY DEFAULT AS IDENTITY")
        elif expr:
            parts.append(f"DEFAULT {expr}")

        if r["not_null"]:
            parts.append("NOT NULL")

        definitions.append("  " + " ".join(parts))

    b2.append(f"CREATE TABLE public.{qi(table)} (")
    b2.append(",\n".join(definitions))
    b2.append(");")
    b2.append("")

for r in sorted(rls, key=lambda x: x["table_name"]):
    if r["rls_enabled"]:
        b2.append(
            f"ALTER TABLE public.{qi(r['table_name'])} ENABLE ROW LEVEL SECURITY;"
        )
    if r["rls_forced"]:
        b2.append(
            f"ALTER TABLE public.{qi(r['table_name'])} FORCE ROW LEVEL SECURITY;"
        )

b2.append("")
b2.append("COMMIT;")

(OUT / "B2-tables.sql").write_text("\n".join(b2) + "\n")

# ============================================================
# B3
# ============================================================
b3 = []
b3.append("-- AUTO-GENERATED FUN Profile baseline")
b3.append("-- B3: constraints + standalone indexes")
b3.append("BEGIN;")
b3.append("")

# PK/U/C first
order = {"p": 0, "u": 1, "c": 2, "f": 3}

for r in sorted(
    constraints,
    key=lambda x: (
        order.get(x["constraint_type"], 99),
        x["table_name"],
        x["constraint_name"]
    )
):
    b3.append(
        f"ALTER TABLE public.{qi(r['table_name'])} "
        f"ADD CONSTRAINT {qi(r['constraint_name'])} {r['definition']};"
    )

b3.append("")

for r in indexes:
    b3.append(r["index_definition"].rstrip(";") + ";")

b3.append("")
b3.append("COMMIT;")

(OUT / "B3-constraints-indexes.sql").write_text("\n".join(b3) + "\n")

# ============================================================
# REPORT
# ============================================================
print("Generated:")
for name in [
    "B1-foundation.sql",
    "B2-tables.sql",
    "B3-constraints-indexes.sql",
]:
    p = OUT / name
    print(f" - {name}: {p.stat().st_size:,} bytes")

print()
print("Expected counts:")
print(" enums:", len(enums))
print(" sequences:", len(seqs))
print(" tables:", len(by_table))
print(" columns:", len(cols))
print(" constraints:", len(constraints))
print(" indexes:", len(indexes))
print(" rls tables:", sum(1 for x in rls if x["rls_enabled"]))
